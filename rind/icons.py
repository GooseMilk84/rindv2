def svg(name: str, color: str = "#ffffff", stroke: float = 1.8) -> bytes:
    body = P.get(name, P["file"])
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" '
        f'stroke-width="{stroke}" stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    ).encode()


@lru_cache(maxsize=512)
def _renderer(name: str, color: str, stroke: float) -> QSvgRenderer:
    return QSvgRenderer(QByteArray(svg(name, color, stroke)))


def draw(p: QPainter, rect: QRectF, name: str, color: str = "#ffffff", stroke: float = 1.8):
    _renderer(name, color, stroke).render(p, rect)


@lru_cache(maxsize=512)
def pixmap(name: str, color: str = "#ededf0", size: int = 18, dpr: float = 2.0) -> QPixmap:
    pm = QPixmap(int(size * dpr), int(size * dpr))
    pm.fill(Qt.GlobalColor.transparent)
    p = QPainter(pm)
    p.setRenderHint(QPainter.RenderHint.Antialiasing)
    draw(p, QRectF(0, 0, size * dpr, size * dpr), name, color)
    p.end()
    pm.setDevicePixelRatio(dpr)
    return pm


def icon(name: str, color: str = "#ededf0", size: int = 18) -> QIcon:
    return QIcon(pixmap(name, color, size))
